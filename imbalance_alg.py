# 9. FEATURE RANKING FUNCTIONS
#
# IMPORTANT:
# These functions are called ONLY with outer-training data.
# Therefore, the outer test fold cannot influence feature ranking.
# ============================================================

def calculate_feature_rankings(
    X_train,
    y_train,
    strategy,
    seed=42,
):

    # Resampling only the supplied training data.
    X_res, y_res = apply_strategy(
        X_train,
        y_train,
        strategy,
    )

    # Scaling only the supplied training data.
    scaler = StandardScaler()

    X_res = pd.DataFrame(
        scaler.fit_transform(X_res),
        columns=X_res.columns,
    )

    # --------------------------------------------------------
    # Mutual Information
    # --------------------------------------------------------
    mi_scores = mutual_info_classif(
        X_res,
        y_res,
        random_state=seed,
    )

    mi_rank = (
        pd.Series(
            mi_scores,
            index=X_res.columns,
        )
        .sort_values(ascending=False)
    )

    mi_rank.to_csv(
        "rank_mutual_info_outer_training.csv"
    )

    # --------------------------------------------------------
    # Correlation
    # --------------------------------------------------------
    corr_rank = (
        abs(
            pd.concat(
                [
                    X_res,
                    y_res.rename("diabetic"),
                ],
                axis=1,
            )
            .corr()["diabetic"]
        )
        .drop("diabetic")
        .sort_values(ascending=False)
    )

    corr_rank.to_csv(
        "rank_correlation_outer_training.csv"
    )

    # --------------------------------------------------------
    # Random Forest Importance
    # --------------------------------------------------------
    rf = RandomForestClassifier(
        n_estimators=500,
        class_weight="balanced",
        random_state=seed,
        n_jobs=-1,
    )

    rf.fit(
        X_res,
        y_res,
    )

    rf_rank = (
        pd.Series(
            rf.feature_importances_,
            index=X_res.columns,
        )
        .sort_values(ascending=False)
    )

    rf_rank.to_csv(
        "rank_random_forest_outer_training.csv"
    )

    # --------------------------------------------------------
    # Boruta
    # --------------------------------------------------------
    rfc = RandomForestClassifier(
        n_estimators=200,
        n_jobs=-1,
        class_weight="balanced",
        max_depth=6,
        random_state=seed,
    )

    boruta = BorutaPy(
        rfc,
        n_estimators="auto",
        random_state=seed,
    )

    boruta.fit(
        X_res.values,
        y_res.values,
    )

    boruta_rank = (
        pd.Series(
            boruta.ranking_,
            index=X_res.columns,
        )
        .sort_values()
    )

    boruta_rank.to_csv(
        "rank_boruta_outer_training.csv"
    )

    # --------------------------------------------------------
    # SHAP
    # --------------------------------------------------------
    background = shap.kmeans(
        X_res,
        min(10, len(X_res)),
    )

    shap_explainer = shap.KernelExplainer(
        rf.predict_proba,
        background,
    )

    sample_n = min(200, len(X_res))

    shap_values = shap_explainer.shap_values(
        X_res.iloc[:sample_n],
        nsamples=100,
    )

    if isinstance(shap_values, list):
        shap_class1 = shap_values[1]
    else:
        shap_values = np.asarray(shap_values)

        if shap_values.ndim == 3:
            shap_class1 = shap_values[:, :, 1]
        else:
            shap_class1 = shap_values

    shap_importance = np.abs(
        shap_class1
    ).mean(axis=0)

    shap_rank = (
        pd.Series(
            shap_importance,
            index=X_res.columns,
        )
        .sort_values(ascending=False)
    )

    shap_rank.to_csv(
        "rank_shap_outer_training.csv"
    )

    # --------------------------------------------------------
    # LIME
    # --------------------------------------------------------
    lime_explainer = LimeTabularExplainer(
        X_res.values,
        feature_names=X_res.columns.tolist(),
        class_names=[
            "non-diabetic",
            "diabetic",
        ],
        discretize_continuous=True,
        random_state=seed,
    )

    importance = np.zeros(
        X_res.shape[1]
    )

    for i in range(
        min(100, len(X_res))
    ):

        exp = lime_explainer.explain_instance(
            X_res.iloc[i].values,
            rf.predict_proba,
            num_features=X_res.shape[1],
        )

        for feat, val in exp.as_list():

            for f in X_res.columns:

                if f in feat:
                    importance[
                        X_res.columns.get_loc(f)
                    ] += abs(val)
                    break

    lime_rank = (
        pd.Series(
            importance,
            index=X_res.columns,
        )
        .sort_values(ascending=False)
    )

    lime_rank.to_csv(
        "rank_lime_outer_training.csv"
    )

    # --------------------------------------------------------
    # PDI
    # --------------------------------------------------------
    rf_pdi = RandomForestClassifier(
        n_estimators=500,
        class_weight="balanced",
        random_state=seed,
        n_jobs=-1,
    )

    rf_pdi.fit(
        X_res,
        y_res,
    )

    pdi_result = permutation_importance(
        rf_pdi,
        X_res,
        y_res,
        n_repeats=20,
        random_state=seed,
        scoring="accuracy",
        n_jobs=-1,
    )

    pdi_rank = (
        pd.Series(
            pdi_result.importances_mean,
            index=X_res.columns,
        )
        .sort_values(ascending=False)
    )

    pdi_rank.to_csv(
        "rank_pdi_outer_training.csv"
    )

    return {
        "MutualInfo": mi_rank,
        "Correlation": corr_rank,
        "RandomForest": rf_rank,
        "SHAP": shap_rank,
        "LIME": lime_rank,
        "PDI": pdi_rank,
        "Boruta": boruta_rank,
    }, X_res, y_res


