# 10. FEATURE-RANKING + GREEDY XGBOOST SELECTION
#
# This is performed separately inside every outer training fold.
# The outer test fold is NEVER supplied to this procedure.
# ============================================================

def greedy_xgb_selection(
    ranking_methods,
    X_res,
    y_res,
    seed=42,
):

    # --------------------------------------------------------
    # Top-6 extraction
    # --------------------------------------------------------
    top_features = {
        name: ranking.index[:TOP_K].tolist()
        for name, ranking
        in ranking_methods.items()
    }

    # --------------------------------------------------------
    # Histogram of Top-6 features
    # --------------------------------------------------------
    feature_counter = Counter()

    for feats in top_features.values():
        feature_counter.update(feats)

    hist_df = (
        pd.DataFrame.from_dict(
            feature_counter,
            orient="index",
            columns=["Frequency"],
        )
        .sort_values(
            by="Frequency",
            ascending=False,
        )
    )

    # --------------------------------------------------------
    # Global ranked feature list
    # --------------------------------------------------------
    rank_positions = {}

    for ranking in ranking_methods.values():

        for rank, feat in enumerate(
            ranking.index[:TOP_K],
            start=1,
        ):
            rank_positions.setdefault(
                feat,
                [],
            ).append(rank)

    ranked_features = pd.DataFrame(
        {
            "Frequency": hist_df["Frequency"],
            "MeanRank": {
                f: np.mean(rank_positions[f])
                for f in hist_df.index
            },
        }
    ).sort_values(
        by=["Frequency", "MeanRank"],
        ascending=[False, True],
    )

    global_feature_list = (
        ranked_features.index.tolist()
    )

    # --------------------------------------------------------
    # Greedy XGBoost
    # --------------------------------------------------------
    selected_features = []
    best_f1 = 0.0
    f1_progress = []

    greedy_cv = StratifiedKFold(
        n_splits=N_INNER_SPLITS,
        shuffle=True,
        random_state=seed,
    )

    for feat in global_feature_list:

        candidate = (
            selected_features + [feat]
        )

        X_sub = X_res[candidate]

        f1_scores = []

        for train_idx, test_idx in greedy_cv.split(
            X_sub,
            y_res,
        ):

            X_train_g = X_sub.iloc[train_idx]
            y_train_g = y_res.iloc[train_idx]

            X_test_g = X_sub.iloc[test_idx]
            y_test_g = y_res.iloc[test_idx]

            model = Pipeline(
                [
                    (
                        "scaler",
                        StandardScaler(),
                    ),
                    (
                        "xgb",
                        make_xgb(y_train_g),
                    ),
                ]
            )

            model.fit(
                X_train_g,
                y_train_g,
            )

            pred = model.predict(
                X_test_g
            )

            f1_scores.append(
                f1_score(
                    y_test_g,
                    pred,
                    zero_division=0,
                )
            )

        mean_f1 = float(
            np.mean(f1_scores)
        )

        if (
            len(selected_features) == 0
            or mean_f1 >= best_f1
        ):
            selected_features.append(feat)
            best_f1 = mean_f1
            f1_progress.append(mean_f1)

    # --------------------------------------------------------
    # Ablation feature sets
    # --------------------------------------------------------
    top1_union = list(
        set(
            r[0]
            for r in top_features.values()
        )
    )

    top3_union = list(
        set(
            f
            for r in top_features.values()
            for f in r[:3]
        )
    )

    top5_union = list(
        set(
            f
            for r in top_features.values()
            for f in r[:5]
        )
    )

    top3_intersection = list(
        set.intersection(
            *(
                set(r[:3])
                for r in top_features.values()
            )
        )
    )

    feature_sets = {
        "Proposed": top3_union,
        "Top-1 Union": top1_union,
        "Top-3 Union": selected_features,
        "Top-5 Union": top5_union,
        "Top-3 Intersection": top3_intersection,
    }

    feature_sets = {
        k: v
        for k, v
        in feature_sets.items()
        if len(v) > 0
    }

    return (
        top_features,
        ranked_features,
        selected_features,
        feature_sets,
        f1_progress,
    )


# ============================================================
# 11. OUTER-TEST EVALUATION OF FEATURE SETS
#
# Feature rankings and feature-set construction are done using
# outer-training data only.
#
# Feature-set comparison/selection uses inner CV.
# The final chosen feature set is then evaluated ONCE on outer test.
# ============================================================

def evaluate_feature_set_inner(
    X_train,
    y_train,
    features,
    strategy,
    seed,
):

    inner_cv = StratifiedKFold(
        n_splits=N_INNER_SPLITS,
        shuffle=True,
        random_state=seed,
    )

    scores = []

    for train_idx, val_idx in inner_cv.split(
        X_train,
        y_train,
    ):

        X_it = X_train.iloc[train_idx][features]
        y_it = y_train.iloc[train_idx]

        X_iv = X_train.iloc[val_idx][features]
        y_iv = y_train.iloc[val_idx]

        X_res, y_res = apply_strategy(
            X_it,
            y_it,
            strategy,
        )

        model = Pipeline(
            [
                (
                    "scaler",
                    StandardScaler(),
                ),
                (
                    "xgb",
                    make_xgb(y_it),
                ),
            ]
        )

        model.fit(
            X_res,
            y_res,
        )

        pred = model.predict(
            X_iv
        )

        scores.append(
            f1_score(
                y_iv,
                pred,
                zero_division=0,
            )
        )

    return float(
        np.mean(scores)
    )


def run_feature_nested_evaluation():

    records = []
    selected_feature_records = []

    for repeat_no, seed in enumerate(
        RANDOM_SEEDS,
        start=1,
    ):

        outer_cv = StratifiedKFold(
            n_splits=N_OUTER_SPLITS,
            shuffle=True,
            random_state=seed,
        )

        for fold_no, (
            outer_train_idx,
            outer_test_idx,
        ) in enumerate(
            outer_cv.split(X, y),
            start=1,
        ):

            X_outer_train = X.iloc[
                outer_train_idx
            ].copy()

            y_outer_train = y.iloc[
                outer_train_idx
            ].copy()

            X_outer_test = X.iloc[
                outer_test_idx
            ].copy()

            y_outer_test = y.iloc[
                outer_test_idx
            ].copy()

            # ------------------------------------------------
            # Feature ranking ONLY on outer training data.
            # ------------------------------------------------
            rankings, X_res_rank, y_res_rank = (
                calculate_feature_rankings(
                    X_outer_train,
                    y_outer_train,
                    RANKING_STRATEGY,
                    seed,
                )
            )

            (
                top_features,
                ranked_features,
                greedy_features,
                feature_sets,
                f1_progress,
            ) = greedy_xgb_selection(
                rankings,
                X_res_rank,
                y_res_rank,
                seed,
            )

            # ------------------------------------------------
            # Select the final feature set by INNER CV only.
            # ------------------------------------------------
            inner_feature_scores = {}

            for name, features in feature_sets.items():

                inner_feature_scores[name] = (
                    evaluate_feature_set_inner(
                        X_outer_train,
                        y_outer_train,
                        features,
                        RANKING_STRATEGY,
                        seed,
                    )
                )

            selected_feature_set_name = max(
                inner_feature_scores,
                key=inner_feature_scores.get,
            )

            selected_features = feature_sets[
                selected_feature_set_name
            ]

            # Save the feature-selection information.
            selected_feature_records.append(
                {
                    "Repeat": repeat_no,
                    "Seed": seed,
                    "OuterFold": fold_no,
                    "Strategy": RANKING_STRATEGY,
                    "SelectedFeatureSet":
                        selected_feature_set_name,
                    "SelectedFeatures":
                        "|".join(selected_features),
                    **{
                        f"InnerF1_{k}": v
                        for k, v
                        in inner_feature_scores.items()
                    },
                }
            )

            # ------------------------------------------------
            # Final outer-training fit.
            # ------------------------------------------------
            X_ot = X_outer_train[
                selected_features
            ]

            X_oe = X_outer_test[
                selected_features
            ]

            X_res_final, y_res_final = (
                apply_strategy(
                    X_ot,
                    y_outer_train,
                    RANKING_STRATEGY,
                )
            )

            final_model = Pipeline(
                [
                    (
                        "scaler",
                        StandardScaler(),
                    ),
                    (
                        "xgb",
                        make_xgb(
                            y_outer_train
                        ),
                    ),
                ]
            )

            final_model.fit(
                X_res_final,
                y_res_final,
            )

            # ------------------------------------------------
            # OUTER TEST: final unbiased evaluation.
            # ------------------------------------------------
            y_pred = final_model.predict(
                X_oe
            )

            metrics = evaluate_predictions(
                y_outer_test,
                y_pred,
            )

            records.append(
                {
                    "Repeat": repeat_no,
                    "Seed": seed,
                    "OuterFold": fold_no,
                    "Strategy": RANKING_STRATEGY,
                    "SelectedFeatureSet":
                        selected_feature_set_name,
                    "NFeatures":
                        len(selected_features),
                    "Accuracy":
                        metrics["Accuracy"],
                    "Precision":
                        metrics["Precision"],
                    "Recall":
                        metrics["Recall"],
                    "F1":
                        metrics["F1"],
                }
            )

            print(
                f"[Feature nested CV] "
                f"Repeat {repeat_no:02d}/10 | "
                f"Fold {fold_no}/5 | "
                f"Selected set: "
                f"{selected_feature_set_name:18s} | "
                f"Features: {len(selected_features):2d} | "
                f"Outer F1: {metrics['F1']:.4f}"
            )

    return (
        pd.DataFrame(records),
        pd.DataFrame(selected_feature_records),
    )


