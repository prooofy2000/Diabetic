# 3. IMBALANCE STRATEGIES
# ============================================================

def apply_strategy(X_train, y_train, strategy):
    """
    Resampling is performed ONLY on the current training fold.

    No validation/test data are passed to ADASYN or TomekLinks.
    """
    if strategy == "Original":
        return X_train.copy(), y_train.copy()

    if strategy == "ADASYN":
        sampler = ADASYN(random_state=RANDOM_STATE)
        return sampler.fit_resample(X_train, y_train)

    if strategy == "TomekLinks":
        sampler = TomekLinks()
        return sampler.fit_resample(X_train, y_train)

    if strategy == "ADASYN+TomekLinks":
        X_tmp, y_tmp = ADASYN(
            random_state=RANDOM_STATE
        ).fit_resample(X_train, y_train)

        return TomekLinks().fit_resample(X_tmp, y_tmp)

    raise ValueError(f"Unknown strategy: {strategy}")


strategies = [
    "Original",
    "ADASYN",
    "TomekLinks",
    "ADASYN+TomekLinks",
]


