# 6. OUTER-CV CLASSIFIER SELECTION + FINAL EVALUATION
# ============================================================

outer_classifier_results = []
outer_predictions = {}
outer_confusions = {}

for repeat_no, seed in enumerate(RANDOM_SEEDS, start=1):

    outer_cv = StratifiedKFold(
        n_splits=N_OUTER_SPLITS,
        shuffle=True,
        random_state=seed,
    )

    for fold_no, (outer_train_idx, outer_test_idx) in enumerate(
        outer_cv.split(X, y),
        start=1,
    ):

        X_outer_train = X.iloc[outer_train_idx].copy()
        y_outer_train = y.iloc[outer_train_idx].copy()

        X_outer_test = X.iloc[outer_test_idx].copy()
        y_outer_test = y.iloc[outer_test_idx].copy()

        for strategy in strategies:

            # ------------------------------------------------
            # CLASSIFIER SELECTION:
            # INNER CV ONLY
            # ------------------------------------------------
            selected_classifier, inner_scores = (
                inner_classifier_selection(
                    X_outer_train,
                    y_outer_train,
                    strategy,
                    seed,
                )
            )

            # ------------------------------------------------
            # FINAL FIT:
            # Use ALL outer-training data only.
            # The outer test fold remains untouched.
            # ------------------------------------------------
            X_res, y_res = apply_strategy(
                X_outer_train,
                y_outer_train,
                strategy,
            )

            scaler = StandardScaler()
            X_res_scaled = pd.DataFrame(
                scaler.fit_transform(X_res),
                columns=X_res.columns,
            )

            X_test_scaled = pd.DataFrame(
                scaler.transform(X_outer_test),
                columns=X_outer_test.columns,
                index=X_outer_test.index,
            )

            if selected_classifier == "XGBoost":
                final_model = make_xgb(y_outer_train)
            else:
                final_model = make_models(
                    y_outer_train
                )[selected_classifier]

            final_model.fit(X_res_scaled, y_res)

            # ------------------------------------------------
            # OUTER TEST:
            # Used ONLY here, after all selections are finished.
            # ------------------------------------------------
            y_test_pred = final_model.predict(X_test_scaled)

            metrics = evaluate_predictions(
                y_outer_test,
                y_test_pred,
            )

            record = {
                "Repeat": repeat_no,
                "Seed": seed,
                "OuterFold": fold_no,
                "Strategy": strategy,
                "SelectedClassifier": selected_classifier,
                "Accuracy": metrics["Accuracy"],
                "Precision": metrics["Precision"],
                "Recall": metrics["Recall"],
                "F1": metrics["F1"],
            }

            # Store the complete inner-CV scores for transparency.
            for clf_name, score in inner_scores.items():
                record[f"InnerF1_{clf_name}"] = score

            outer_classifier_results.append(record)

            key = (
                repeat_no,
                fold_no,
                strategy,
            )

            outer_predictions[key] = (
                y_outer_test.to_numpy(),
                y_test_pred,
            )

            outer_confusions[key] = metrics["CM"]

            print(
                f"Repeat {repeat_no:02d}/10 | "
                f"Fold {fold_no}/5 | "
                f"{strategy:20s} | "
                f"Selected: {selected_classifier:18s} | "
                f"Outer F1: {metrics['F1']:.4f}"
            )


