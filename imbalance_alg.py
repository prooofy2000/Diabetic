# 5. INNER-CV CLASSIFIER SELECTION
# ============================================================

def inner_classifier_selection(X_train, y_train, strategy, seed):
    """
    Select the classifier using ONLY inner-CV performance.

    The outer-test fold is not available here.

    For each inner split:
      1. Split the outer-training data.
      2. Apply resampling only to inner-training data.
      3. Fit scaling only to inner-training data.
      4. Fit classifier on inner-training data.
      5. Evaluate on untouched inner-validation data.

    Selection criterion = mean inner-CV F1.
    """

    inner_cv = StratifiedKFold(
        n_splits=N_INNER_SPLITS,
        shuffle=True,
        random_state=seed,
    )

    scores = {
        name: []
        for name in make_models(y_train).keys()
    }

    for inner_train_idx, inner_val_idx in inner_cv.split(X_train, y_train):

        X_inner_train = X_train.iloc[inner_train_idx].copy()
        y_inner_train = y_train.iloc[inner_train_idx].copy()

        X_inner_val = X_train.iloc[inner_val_idx].copy()
        y_inner_val = y_train.iloc[inner_val_idx].copy()

        # Resampling ONLY inside inner-training data.
        X_res, y_res = apply_strategy(
            X_inner_train,
            y_inner_train,
            strategy,
        )

        # Scaling ONLY fitted on inner-training data.
        scaler = StandardScaler()
        X_res_scaled = pd.DataFrame(
            scaler.fit_transform(X_res),
            columns=X_res.columns,
            index=X_res.index,
        )

        X_val_scaled = pd.DataFrame(
            scaler.transform(X_inner_val),
            columns=X_inner_val.columns,
            index=X_inner_val.index,
        )

        for name, model in make_models(y_inner_train).items():

            model.fit(X_res_scaled, y_res)
            y_pred = model.predict(X_val_scaled)

            scores[name].append(
                f1_score(
                    y_inner_val,
                    y_pred,
                    zero_division=0,
                )
            )

    mean_scores = {
        name: float(np.mean(values))
        for name, values in scores.items()
    }

    selected_classifier = max(
        mean_scores,
        key=mean_scores.get,
    )

    return selected_classifier, mean_scores


