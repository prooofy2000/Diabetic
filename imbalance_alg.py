# ============================================================
# 14. WILCOXON TESTS
#
# Compare repeated outer-test F1 values.
#
# IMPORTANT:
# These tests are descriptive comparisons of the 50 outer-test
# evaluations. They are NOT used to select the final model.
# ============================================================

def wilcoxon_against_reference(
    results_df,
    metric="F1",
    reference_name="Proposed",
):

    pivot = results_df.pivot_table(
        index=["Repeat", "OuterFold"],
        columns="SelectedFeatureSet",
        values=metric,
    )

    if reference_name not in pivot.columns:
        print(
            f"Reference '{reference_name}' "
            "not available."
        )
        return

    reference = pivot[
        reference_name
    ].dropna()

    output = []

    for name in pivot.columns:

        if name == reference_name:
            continue

        current = pivot[
            name
        ].dropna()

        common = reference.index.intersection(
            current.index
        )

        if len(common) < 2:
            continue

        a = reference.loc[common]
        b = current.loc[common]

        try:
            stat, p = wilcoxon(
                a,
                b,
                zero_method="wilcox",
                alternative="two-sided",
            )
        except ValueError:
            stat, p = np.nan, np.nan

        output.append(
            {
                "Reference": reference_name,
                "Compared": name,
                "N": len(common),
                "WilcoxonStatistic": stat,
                "PValue": p,
            }
        )

    return pd.DataFrame(output)


